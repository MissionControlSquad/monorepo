import { gql } from "urql";

export const CREATE_QUEUE_ITEM = gql`
  mutation CreateQueueItem(
    $agentId: String!
    $title: String!
    $description: String
    $notes: String
    $priority: String
    $relatedTaskId: String
    $itemType: String
    $autoGenerated: Boolean
    $generatedFrom: String
  ) {
    createQueueItem(
      agentId: $agentId
      title: $title
      description: $description
      notes: $notes
      priority: $priority
      relatedTaskId: $relatedTaskId
      itemType: $itemType
      autoGenerated: $autoGenerated
      generatedFrom: $generatedFrom
    ) {
      id
      agentId
      title
      description
      notes
      status
      priority
      relatedTaskId
      projectId
      itemType
      autoGenerated
      generatedFrom
      order
      createdAt
    }
  }
`;

export const UPDATE_QUEUE_ITEM_STATUS = gql`
  mutation UpdateQueueItemStatus($id: String!, $status: String!, $notes: String) {
    updateQueueItemStatus(id: $id, status: $status, notes: $notes) {
      id
      agentId
      title
      status
      priority
      notes
      startedAt
      completedAt
      order
    }
  }
`;

