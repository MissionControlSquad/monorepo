"use client";

import { useState } from "react";
import Link from "next/link";
import { useQuery, useMutation } from "urql";
import { toast } from "sonner";
import { ListTodo } from "lucide-react";
import { AGENT_QUEUE_ACTIVE_QUERY } from "@/lib/graphql/queries";
import { UPDATE_QUEUE_ITEM_STATUS, DELETE_QUEUE_ITEM } from "@/lib/graphql/mutations";
import { useFeatureFlag } from "@/components/context/FeatureFlagContext";
import { FLAG_KEYS, QueueItemStatus } from "@agentcenter/utils";
import { Card, Button, Badge } from "@/components/ui";

// Domain 5: the agent's own active work queue — the follow-ups / task-breakdowns it generates for
// itself. Lets a human see and manage it (mark done, skip, remove). Agent-profile card; AGENT_QUEUE-
// gated; self-hides when empty. No new backend.
interface QueueItem {
  id: string;
  title: string;
  description?: string | null;
  status: string;
  priority?: string | null;
  itemType?: string | null;
  autoGenerated?: boolean | null;
  relatedTaskId?: string | null;
  createdAt: string;
}

type BadgeVariant = "gray" | "yellow" | "green" | "blue" | "orange";
const STATUS_VARIANT: Record<string, BadgeVariant> = {
  pending: "yellow",
  in_progress: "blue",
  blocked: "orange",
};

export function AgentQueueCard({ agentId }: { agentId: string }) {
  const enabled = useFeatureFlag(FLAG_KEYS.AGENT_QUEUE);
  const [{ data }, refetch] = useQuery<{ agentQueueActive: QueueItem[] }>({
    query: AGENT_QUEUE_ACTIVE_QUERY,
    variables: { agentId },
    pause: !enabled,
  });
  const [, updateStatus] = useMutation(UPDATE_QUEUE_ITEM_STATUS);
  const [, remove] = useMutation(DELETE_QUEUE_ITEM);
  const [busy, setBusy] = useState<string | null>(null);

  if (!enabled) return null;
  const items = data?.agentQueueActive ?? [];
  if (items.length === 0) return null;
  const refresh = () => refetch({ requestPolicy: "network-only" });

  async function setStatus(id: string, status: string, ok: string) {
    setBusy(id);
    try {
      const res = await updateStatus({ id, status });
      if (res.error) toast.error(res.error.graphQLErrors[0]?.message ?? "Failed");
      else {
        toast.success(ok);
        refresh();
      }
    } finally {
      setBusy(null);
    }
  }

  async function onRemove(id: string) {
    setBusy(id);
    try {
      const res = await remove({ id });
      if (res.error) toast.error(res.error.graphQLErrors[0]?.message ?? "Failed");
      else {
        toast.success("Removed");
        refresh();
      }
    } finally {
      setBusy(null);
    }
  }

  return (
    <Card className="space-y-3 p-4">
      <div className="flex items-center gap-2">
        <ListTodo className="h-4 w-4 text-muted-foreground" />
        <h2 className="text-sm font-semibold text-foreground">Work queue</h2>
        <span className="ml-auto text-xs text-muted-foreground">{items.length}</span>
      </div>

      <ul className="space-y-2">
        {items.map((q) => (
          <li key={q.id} className="rounded-lg border border-border p-2.5">
            <div className="flex flex-wrap items-center gap-2">
              <Badge variant={STATUS_VARIANT[q.status] ?? "gray"} size="sm">
                {q.status.replace(/_/g, " ")}
              </Badge>
              {q.itemType && (
                <Badge variant="gray" size="sm">
                  {q.itemType.replace(/_/g, " ")}
                </Badge>
              )}
              {q.autoGenerated && (
                <span className="text-[10px] uppercase tracking-wide text-muted-foreground">
                  auto
                </span>
              )}
              <span className="min-w-0 flex-1 truncate text-sm font-medium text-foreground">
                {q.relatedTaskId ? (
                  <Link href={`/task/${q.relatedTaskId}`} className="hover:underline">
                    {q.title}
                  </Link>
                ) : (
                  q.title
                )}
              </span>
            </div>
            {q.description && (
              <p className="mt-1 truncate text-xs text-muted-foreground">{q.description}</p>
            )}
            <div className="mt-2 flex gap-2">
              <Button
                size="sm"
                disabled={busy === q.id}
                onClick={() => setStatus(q.id, QueueItemStatus.COMPLETED, "Marked done")}
              >
                Done
              </Button>
              <Button
                size="sm"
                variant="secondary"
                disabled={busy === q.id}
                onClick={() => setStatus(q.id, QueueItemStatus.SKIPPED, "Skipped")}
              >
                Skip
              </Button>
              <button
                className="ml-auto text-xs text-muted-foreground transition hover:text-destructive disabled:opacity-50"
                disabled={busy === q.id}
                onClick={() => onRemove(q.id)}
              >
                Remove
              </button>
            </div>
          </li>
        ))}
      </ul>
    </Card>
  );
}
