import { builder } from "../builder";

builder.prismaObject("AgentQueueItem", {
  fields: (t) => ({
    id: t.exposeID("id"),
    agentId: t.exposeString("agentId"),
    title: t.exposeString("title"),
    description: t.exposeString("description", { nullable: true }),
    notes: t.exposeString("notes", { nullable: true }),
    status: t.exposeString("status"),
    priority: t.exposeString("priority"),
    relatedTaskId: t.exposeString("relatedTaskId", { nullable: true }),
    projectId: t.exposeString("projectId", { nullable: true }),
    parentQueueItemId: t.exposeString("parentQueueItemId", { nullable: true }),
    itemType: t.exposeString("itemType"),
    autoGenerated: t.exposeBoolean("autoGenerated"),
    generatedFrom: t.exposeString("generatedFrom", { nullable: true }),
    createdAt: t.expose("createdAt", { type: "DateTime" }),
    startedAt: t.expose("startedAt", { type: "DateTime", nullable: true }),
    completedAt: t.expose("completedAt", { type: "DateTime", nullable: true }),
    dueDate: t.expose("dueDate", { type: "DateTime", nullable: true }),
    order: t.exposeInt("order"),

    agent: t.relation("agent"),
    relatedTask: t.relation("relatedTask", { nullable: true }),
    project: t.relation("project", { nullable: true }),
    parentQueueItem: t.relation("parentQueueItem", { nullable: true }),
    childQueueItems: t.relation("childQueueItems"),
  }),
});
