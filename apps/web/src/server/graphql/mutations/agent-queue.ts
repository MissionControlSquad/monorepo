import { builder } from "../builder";
import { requireFeature } from "../require-feature";
import { FLAG_KEYS } from "../../../lib/feature-flag-keys";
import { agentModel, agentQueueItemModel } from "../../models";
import { taskModel } from "../../models/task";

builder.mutationField("createQueueItem", (t) =>
  t.prismaField({
    type: "AgentQueueItem",
    args: {
      agentId: t.arg.string({ required: true }),
      title: t.arg.string({ required: true }),
      description: t.arg.string(),
      notes: t.arg.string(),
      priority: t.arg.string(),
      relatedTaskId: t.arg.string(),
      itemType: t.arg.string(),
      autoGenerated: t.arg.boolean(),
      generatedFrom: t.arg.string(),
    },
    resolve: async (query, _root, args) => {
      await requireFeature(FLAG_KEYS.AGENT_QUEUE);
      // Get max order for this agent
      const lastItem = await agentQueueItemModel.findOne({
        where: { agentId: args.agentId },
        orderBy: { order: "desc" },
        select: { order: true },
      });
      const nextOrder = (lastItem?.order ?? 0) + 1;

      let projectId: string | undefined;
      if (args.relatedTaskId) {
        const task = await taskModel.findById(args.relatedTaskId, {
          select: { projectId: true },
        });
        projectId = task?.projectId ?? undefined;
      }

      const item = await agentQueueItemModel.delegate.create({
        ...query,
        data: {
          agentId: args.agentId,
          title: args.title,
          description: args.description ?? undefined,
          notes: args.notes ?? undefined,
          priority: (args.priority as any) ?? "medium",
          relatedTaskId: args.relatedTaskId ?? undefined,
          projectId,
          itemType: (args.itemType as any) ?? "action",
          autoGenerated: args.autoGenerated ?? false,
          generatedFrom: args.generatedFrom ?? undefined,
          order: nextOrder,
        },
      });

      const agent = await agentModel.findById(args.agentId, {
        select: { name: true },
      });

      await agentQueueItemModel.emitItemCreated(item, {
        agentName: agent?.name ?? "",
      });

      return item;
    },
  }),
);

builder.mutationField("updateQueueItemStatus", (t) =>
  t.prismaField({
    type: "AgentQueueItem",
    args: {
      id: t.arg.string({ required: true }),
      status: t.arg.string({ required: true }),
      notes: t.arg.string(),
    },
    resolve: async (query, _root, args) => {
      await requireFeature(FLAG_KEYS.AGENT_QUEUE);
      const item = await agentQueueItemModel.findByIdOrThrow(args.id);

      const now = new Date();
      const data: Record<string, unknown> = {
        status: args.status as any,
      };

      if (args.notes) {
        const existing = item.notes ?? "";
        data.notes = existing
          ? `${existing}\n\n---\n${now.toISOString()}: ${args.notes}`
          : args.notes;
      }

      if (args.status === "in_progress" && !item.startedAt) {
        data.startedAt = now;
      }
      if (args.status === "completed" || args.status === "skipped") {
        data.completedAt = now;
      }

      const updated = await agentQueueItemModel.delegate.update({
        ...query,
        where: { id: args.id },
        data,
      });

      const agent = await agentModel.findById(item.agentId, {
        select: { name: true },
      });

      await agentQueueItemModel.emitItemStatusChanged(item, {
        agentName: agent?.name ?? "",
        newStatus: args.status,
      });

      return updated;
    },
  }),
);

builder.mutationField("updateQueueItem", (t) =>
  t.prismaField({
    type: "AgentQueueItem",
    args: {
      id: t.arg.string({ required: true }),
      title: t.arg.string(),
      description: t.arg.string(),
      notes: t.arg.string(),
      priority: t.arg.string(),
    },
    resolve: async (query, _root, args) => {
      await requireFeature(FLAG_KEYS.AGENT_QUEUE);
      return agentQueueItemModel.delegate.update({
        ...query,
        where: { id: args.id },
        data: {
          ...(args.title ? { title: args.title } : {}),
          ...(args.description ? { description: args.description } : {}),
          ...(args.notes ? { notes: args.notes } : {}),
          ...(args.priority ? { priority: args.priority as any } : {}),
        },
      });
    },
  }),
);

builder.mutationField("deleteQueueItem", (t) =>
  t.field({
    type: "Boolean",
    args: { id: t.arg.string({ required: true }) },
    resolve: async (_root, args) => {
      await requireFeature(FLAG_KEYS.AGENT_QUEUE);
      await agentQueueItemModel.deleteById(args.id);
      return true;
    },
  }),
);
