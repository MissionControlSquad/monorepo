import { on } from "../bus";
import {
  EventTypes,
  Priority,
  QueueItemStatus,
  QueueItemType,
  QueueItemGeneratedFrom,
} from "../../constants";
import { agentQueueItemModel } from "../../models";

// Mark review queue items as completed when task is approved or rejected
on(EventTypes.TASK_APPROVED, async (e) => {
  if (e.type !== EventTypes.TASK_APPROVED) return;

  // Find and complete any review-related queue items
  for (const agentId of e.assigneeIds) {
    const reviewItems = await agentQueueItemModel.findMany({
      where: {
        agentId,
        relatedTaskId: e.taskId,
        status: { in: [QueueItemStatus.PENDING, QueueItemStatus.IN_PROGRESS] },
      },
    });

    if (reviewItems.length > 0) {
      await agentQueueItemModel.delegate.updateMany({
        where: { id: { in: reviewItems.map((i) => i.id) } },
        data: { status: QueueItemStatus.COMPLETED, completedAt: new Date() },
      });
    }
  }
});

on(EventTypes.TASK_REJECTED, async (e) => {
  if (e.type !== EventTypes.TASK_REJECTED) return;

  // Mark review items as completed
  for (const agentId of e.assigneeIds) {
    const reviewItems = await agentQueueItemModel.findMany({
      where: {
        agentId,
        relatedTaskId: e.taskId,
        status: { in: [QueueItemStatus.PENDING, QueueItemStatus.IN_PROGRESS] },
      },
    });

    if (reviewItems.length > 0) {
      await agentQueueItemModel.delegate.updateMany({
        where: { id: { in: reviewItems.map((i) => i.id) } },
        data: { status: QueueItemStatus.COMPLETED, completedAt: new Date() },
      });
    }

    // Create high-priority action items for rejected tasks
    const lastItem = await agentQueueItemModel.findOne({
      where: { agentId },
      orderBy: { order: "desc" },
      select: { order: true },
    });
    const nextOrder = (lastItem?.order ?? 0) + 1;

    const changesList = e.changesNeeded.map((c, i) => `${i + 1}. ${c}`).join("\n");

    await agentQueueItemModel.create({
      data: {
        agentId,
        title: `Address review feedback: ${e.title}`,
        description: `**Rejection reason:** ${e.rejectionReason}\n\n**Changes needed:**\n${changesList}`,
        status: QueueItemStatus.PENDING,
        priority: Priority.HIGH,
        relatedTaskId: e.taskId,
        itemType: QueueItemType.ACTION,
        autoGenerated: true,
        generatedFrom: QueueItemGeneratedFrom.REVIEW_REJECTION,
        order: nextOrder,
      },
    });
  }
});
