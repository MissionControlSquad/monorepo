export const dynamic = "force-dynamic";

import { taskModel } from "@/server/models/task";
import { agentQueueItemModel } from "@/server/models";
import { resolveAgent } from "../_lib/resolve-agent";
import { successResponse, errorResponse, handleError } from "../_lib/json-response";
import { validateBody, createQueueItemSchema } from "../_lib/validation";
import { log } from "../_lib/logger";
import { isSystemShutdown } from "@/server/system-settings";
import { isFeatureEnabled } from "@/server/feature-flags";
import { FLAG_KEYS } from "@agentcenter/utils";

export async function GET(request: Request) {
  try {
    const agent = await resolveAgent(request);

    if (!(await isFeatureEnabled(FLAG_KEYS.AGENT_QUEUE))) {
      return errorResponse("Agent queue feature is not available on your current plan", 403);
    }

    const { searchParams } = new URL(request.url);

    const active = searchParams.get("active") === "true";
    const status = searchParams.get("status");

    const where: Record<string, unknown> = { agentId: agent.id };

    if (active) {
      where.status = { in: ["pending", "in_progress"] };
    } else if (status) {
      where.status = status;
    }

    const limit = Math.min(parseInt(searchParams.get("limit") ?? "200", 10) || 200, 500);
    const offset = Math.max(parseInt(searchParams.get("offset") ?? "0", 10) || 0, 0);

    const items = await agentQueueItemModel.findMany({
      where,
      orderBy: [{ order: "asc" }],
      take: limit,
      skip: offset,
    });

    return successResponse(items);
  } catch (err) {
    return handleError(err);
  }
}

export async function POST(request: Request) {
  try {
    const v = await validateBody(request, createQueueItemSchema);
    if (v.error) return v.error;
    const agent = await resolveAgent(request);

    const {
      title,
      description,
      notes,
      priority,
      relatedTaskId,
      itemType,
      autoGenerated,
      generatedFrom,
    } = v.data;
    if (await isSystemShutdown()) {
      return errorResponse("System is in shutdown mode. No queue items can be created.", 503);
    }

    // Get max order for this agent
    const lastItem = await agentQueueItemModel.findOne({
      where: { agentId: agent.id },
      orderBy: { order: "desc" },
      select: { order: true },
    });
    const nextOrder = (lastItem?.order ?? 0) + 1;

    let projectId: string | undefined;
    if (relatedTaskId) {
      const task = await taskModel.findByIdSelect(relatedTaskId, {
        projectId: true,
      });
      projectId = task?.projectId ?? undefined;
    }

    const item = await agentQueueItemModel.create({
      data: {
        agentId: agent.id,
        title,
        description: description ?? undefined,
        notes: notes ?? undefined,
        priority: (priority as any) ?? "medium",
        relatedTaskId: relatedTaskId ?? undefined,
        projectId,
        itemType: (itemType as any) ?? "action",
        autoGenerated: autoGenerated ?? false,
        generatedFrom: generatedFrom ?? undefined,
        order: nextOrder,
      },
    });

    await agentQueueItemModel.emitItemCreated(item, {
      agentName: agent.name,
    });

    log("queue", `CREATED agent="${agent.name}" item="${title}"`, request);
    return successResponse(item, 201);
  } catch (err) {
    return handleError(err);
  }
}
