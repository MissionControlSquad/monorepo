import {
  View,
  Text,
  TextInput,
  TouchableOpacity,
  ActivityIndicator,
  Alert,
  KeyboardAvoidingView,
  Platform,
  ScrollView,
} from "react-native";
import { useState } from "react";
import { useRouter, useLocalSearchParams } from "expo-router";
import { Ionicons } from "@expo/vector-icons";
import { useAuth } from "../../src/context/AuthContext";

export default function ResetPasswordScreen() {
  const router = useRouter();
  const { serverUrl: savedUrl } = useAuth();
  const params = useLocalSearchParams<{ serverUrl?: string }>();

  const serverUrl = params.serverUrl ?? savedUrl ?? "";

  const [step, setStep] = useState<"info" | "reset">("info");
  const [token, setToken] = useState("");
  const [newPassword, setNewPassword] = useState("");
  const [confirmPassword, setConfirmPassword] = useState("");
  const [showPassword, setShowPassword] = useState(false);
  const [loading, setLoading] = useState(false);

  const handleReset = async () => {
    if (!token.trim()) {
      Alert.alert("Required", "Please enter your reset token.");
      return;
    }
    if (newPassword.length < 8) {
      Alert.alert("Too short", "Password must be at least 8 characters.");
      return;
    }
    if (newPassword !== confirmPassword) {
      Alert.alert("Mismatch", "Passwords do not match.");
      return;
    }
    if (!serverUrl) {
      Alert.alert("Error", "No server URL configured. Go back and enter it on the login screen.");
      return;
    }

    setLoading(true);
    try {
      const res = await fetch(`${serverUrl}/api/auth/reset-password`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ token: token.trim(), newPassword }),
      });

      const data = await res.json() as { success?: boolean; error?: string; autoLogin?: boolean; username?: string };

      if (!res.ok) {
        const msg = res.status === 429
          ? "Too many attempts. Please wait a few minutes and try again."
          : (data.error ?? "Invalid or expired reset link.");
        Alert.alert("Reset Failed", msg);
        return;
      }

      if (data.success && data.autoLogin) {
        Alert.alert(
          "Password Reset",
          "Your password has been reset. Sign in with your new password.",
          [{ text: "Sign In", onPress: () => router.replace("/auth/login") }]
        );
      } else {
        Alert.alert(
          "Password Reset",
          "Your password has been reset successfully.",
          [{ text: "Sign In", onPress: () => router.replace("/auth/login") }]
        );
      }
    } catch {
      Alert.alert("Error", "Network error. Check your connection and try again.");
    } finally {
      setLoading(false);
    }
  };

  if (step === "info") {
    return (
      <ScrollView
        className="flex-1 bg-gray-50 dark:bg-slate-900"
        contentContainerStyle={{ padding: 24, paddingTop: 32, gap: 16, alignItems: "stretch" }}
        contentInsetAdjustmentBehavior="automatic"
        keyboardShouldPersistTaps="handled"
      >
        <View className="items-center mb-2">
          <Ionicons name="key-outline" size={48} color="#2563eb" />
        </View>

        <Text className="text-[22px] font-extrabold text-gray-900 dark:text-slate-100 text-center">
          Reset Password
        </Text>
        <Text className="text-sm text-gray-500 dark:text-slate-400 text-center leading-5">
          Password resets in AgentCenter require a reset token generated by an administrator.
        </Text>

        <View className="bg-white dark:bg-slate-800 rounded-[14px] border border-gray-200 dark:border-slate-700 p-4 gap-3.5">
          <StepRow number="1" text="Contact your AgentCenter administrator and ask them to generate a password reset link for your account." />
          <StepRow number="2" text="They will send you a link or token starting with reset_... - copy the full token." />
          <StepRow number="3" text={'Tap "Enter Reset Token" below and enter the token along with your new password.'} />
        </View>

        <TouchableOpacity
          className="bg-blue-600 dark:bg-blue-500 rounded-xl py-3.5 items-center mt-1"
          onPress={() => setStep("reset")}
          activeOpacity={0.8}
        >
          <Text className="text-white text-base font-semibold">Enter Reset Token</Text>
        </TouchableOpacity>

        <TouchableOpacity
          className="items-center py-2.5"
          onPress={() => router.back()}
          activeOpacity={0.7}
        >
          <Text className="text-[15px] text-gray-500 dark:text-slate-400">Back to Sign In</Text>
        </TouchableOpacity>
      </ScrollView>
    );
  }

  return (
    <KeyboardAvoidingView
      className="flex-1 bg-gray-50 dark:bg-slate-900"
      behavior={Platform.OS === "ios" ? "padding" : undefined}
    >
      <ScrollView
        contentContainerStyle={{ padding: 24, paddingTop: 32, gap: 16, alignItems: "stretch" }}
        contentInsetAdjustmentBehavior="automatic"
        keyboardShouldPersistTaps="handled"
      >
        <View className="items-center mb-2">
          <Ionicons name="lock-closed-outline" size={48} color="#2563eb" />
        </View>

        <Text className="text-[22px] font-extrabold text-gray-900 dark:text-slate-100 text-center">
          Enter New Password
        </Text>
        <Text className="text-sm text-gray-500 dark:text-slate-400 text-center leading-5">
          Paste the reset token from your administrator, then choose a new password.
        </Text>

        <View className="gap-1.5">
          <Text className="text-[13px] font-semibold text-gray-700 dark:text-slate-300">Reset Token</Text>
          <TextInput
            className="bg-white dark:bg-slate-800 border border-gray-200 dark:border-slate-700 rounded-[10px] px-3.5 py-[13px] text-[15px] text-gray-900 dark:text-slate-100 mb-1"
            value={token}
            onChangeText={setToken}
            placeholder="reset_..."
            placeholderTextColor="#9ca3af"
            autoCapitalize="none"
            autoCorrect={false}
            editable={!loading}
          />
        </View>

        <View className="gap-1.5">
          <Text className="text-[13px] font-semibold text-gray-700 dark:text-slate-300">New Password</Text>
          <View className="flex-row items-center gap-2">
            <TextInput
              className="flex-1 bg-white dark:bg-slate-800 border border-gray-200 dark:border-slate-700 rounded-[10px] px-3.5 py-[13px] text-[15px] text-gray-900 dark:text-slate-100"
              value={newPassword}
              onChangeText={setNewPassword}
              placeholder="Min. 8 characters"
              placeholderTextColor="#9ca3af"
              secureTextEntry={!showPassword}
              editable={!loading}
            />
            <TouchableOpacity onPress={() => setShowPassword(!showPassword)} className="p-2">
              <Ionicons name={showPassword ? "eye-off-outline" : "eye-outline"} size={20} color="#6b7280" />
            </TouchableOpacity>
          </View>
        </View>

        <View className="gap-1.5">
          <Text className="text-[13px] font-semibold text-gray-700 dark:text-slate-300">Confirm Password</Text>
          <TextInput
            className="bg-white dark:bg-slate-800 border border-gray-200 dark:border-slate-700 rounded-[10px] px-3.5 py-[13px] text-[15px] text-gray-900 dark:text-slate-100 mb-1"
            value={confirmPassword}
            onChangeText={setConfirmPassword}
            placeholder="Repeat new password"
            placeholderTextColor="#9ca3af"
            secureTextEntry={!showPassword}
            editable={!loading}
          />
        </View>

        <TouchableOpacity
          className={`bg-blue-600 dark:bg-blue-500 rounded-xl py-3.5 items-center mt-1 ${loading ? "opacity-50" : ""}`}
          onPress={handleReset}
          disabled={loading}
          activeOpacity={0.8}
        >
          {loading ? (
            <ActivityIndicator color="#fff" />
          ) : (
            <Text className="text-white text-base font-semibold">Reset Password</Text>
          )}
        </TouchableOpacity>

        <TouchableOpacity
          className="items-center py-2.5"
          onPress={() => setStep("info")}
          activeOpacity={0.7}
        >
          <Text className="text-[15px] text-gray-500 dark:text-slate-400">Back</Text>
        </TouchableOpacity>
      </ScrollView>
    </KeyboardAvoidingView>
  );
}

function StepRow({ number, text }: { number: string; text: string }) {
  return (
    <View className="flex-row gap-3 items-start">
      <View className="w-6 h-6 rounded-full bg-blue-50 dark:bg-blue-900/30 justify-center items-center mt-px shrink-0">
        <Text className="text-[12px] font-bold text-blue-600 dark:text-blue-400">{number}</Text>
      </View>
      <Text className="flex-1 text-[13px] text-gray-700 dark:text-slate-300 leading-[19px]">{text}</Text>
    </View>
  );
}
