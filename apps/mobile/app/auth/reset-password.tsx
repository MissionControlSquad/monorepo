import {
  View,
  Text,
  TextInput,
  TouchableOpacity,
  StyleSheet,
  ActivityIndicator,
  Alert,
  KeyboardAvoidingView,
  Platform,
  ScrollView,
} from "react-native";
import { useState } from "react";
import { useRouter, useLocalSearchParams } from "expo-router";
import { Ionicons } from "@expo/vector-icons";
import { useAuth } from "../../src/context/AuthContext";

export default function ResetPasswordScreen() {
  const router = useRouter();
  const { serverUrl: savedUrl } = useAuth();
  const params = useLocalSearchParams<{ serverUrl?: string }>();

  const serverUrl = params.serverUrl ?? savedUrl ?? "";

  const [step, setStep] = useState<"info" | "reset">("info");
  const [token, setToken] = useState("");
  const [newPassword, setNewPassword] = useState("");
  const [confirmPassword, setConfirmPassword] = useState("");
  const [showPassword, setShowPassword] = useState(false);
  const [loading, setLoading] = useState(false);

  const handleReset = async () => {
    if (!token.trim()) {
      Alert.alert("Required", "Please enter your reset token.");
      return;
    }
    if (newPassword.length < 8) {
      Alert.alert("Too short", "Password must be at least 8 characters.");
      return;
    }
    if (newPassword !== confirmPassword) {
      Alert.alert("Mismatch", "Passwords do not match.");
      return;
    }
    if (!serverUrl) {
      Alert.alert("Error", "No server URL configured. Go back and enter it on the login screen.");
      return;
    }

    setLoading(true);
    try {
      const res = await fetch(`${serverUrl}/api/auth/reset-password`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ token: token.trim(), newPassword }),
      });

      const data = await res.json() as { success?: boolean; error?: string; autoLogin?: boolean; username?: string };

      if (!res.ok) {
        const msg = res.status === 429
          ? "Too many attempts. Please wait a few minutes and try again."
          : (data.error ?? "Invalid or expired reset link.");
        Alert.alert("Reset Failed", msg);
        return;
      }

      if (data.success && data.autoLogin) {
        Alert.alert(
          "Password Reset",
          "Your password has been reset. Sign in with your new password.",
          [{ text: "Sign In", onPress: () => router.replace("/auth/login") }]
        );
      } else {
        Alert.alert(
          "Password Reset",
          "Your password has been reset successfully.",
          [{ text: "Sign In", onPress: () => router.replace("/auth/login") }]
        );
      }
    } catch {
      Alert.alert("Error", "Network error. Check your connection and try again.");
    } finally {
      setLoading(false);
    }
  };

  if (step === "info") {
    return (
      <ScrollView
        style={styles.container}
        contentContainerStyle={styles.content}
        contentInsetAdjustmentBehavior="automatic"
        keyboardShouldPersistTaps="handled"
      >
        <View style={styles.iconWrap}>
          <Ionicons name="key-outline" size={48} color="#2563eb" />
        </View>

        <Text style={styles.title}>Reset Password</Text>
        <Text style={styles.body}>
          Password resets in AgentCenter require a reset token generated by an administrator.
        </Text>

        <View style={styles.steps}>
          <StepRow number="1" text="Contact your AgentCenter administrator and ask them to generate a password reset link for your account." />
          <StepRow number="2" text="They will send you a link or token starting with reset_... - copy the full token." />
          <StepRow number="3" text={'Tap "Enter Reset Token" below and enter the token along with your new password.'} />
        </View>

        <TouchableOpacity
          style={styles.primaryBtn}
          onPress={() => setStep("reset")}
          activeOpacity={0.8}
        >
          <Text style={styles.primaryBtnText}>Enter Reset Token</Text>
        </TouchableOpacity>

        <TouchableOpacity
          style={styles.backBtn}
          onPress={() => router.back()}
          activeOpacity={0.7}
        >
          <Text style={styles.backBtnText}>Back to Sign In</Text>
        </TouchableOpacity>
      </ScrollView>
    );
  }

  return (
    <KeyboardAvoidingView
      style={styles.container}
      behavior={Platform.OS === "ios" ? "padding" : undefined}
    >
      <ScrollView
        contentContainerStyle={styles.content}
        contentInsetAdjustmentBehavior="automatic"
        keyboardShouldPersistTaps="handled"
      >
        <View style={styles.iconWrap}>
          <Ionicons name="lock-closed-outline" size={48} color="#2563eb" />
        </View>

        <Text style={styles.title}>Enter New Password</Text>
        <Text style={styles.body}>Paste the reset token from your administrator, then choose a new password.</Text>

        <View style={styles.field}>
          <Text style={styles.label}>Reset Token</Text>
          <TextInput
            style={styles.input}
            value={token}
            onChangeText={setToken}
            placeholder="reset_..."
            placeholderTextColor="#9ca3af"
            autoCapitalize="none"
            autoCorrect={false}
            editable={!loading}
          />
        </View>

        <View style={styles.field}>
          <Text style={styles.label}>New Password</Text>
          <View style={styles.passwordRow}>
            <TextInput
              style={[styles.input, { flex: 1, marginBottom: 0 }]}
              value={newPassword}
              onChangeText={setNewPassword}
              placeholder="Min. 8 characters"
              placeholderTextColor="#9ca3af"
              secureTextEntry={!showPassword}
              editable={!loading}
            />
            <TouchableOpacity onPress={() => setShowPassword(!showPassword)} style={styles.eyeBtn}>
              <Ionicons name={showPassword ? "eye-off-outline" : "eye-outline"} size={20} color="#6b7280" />
            </TouchableOpacity>
          </View>
        </View>

        <View style={styles.field}>
          <Text style={styles.label}>Confirm Password</Text>
          <TextInput
            style={styles.input}
            value={confirmPassword}
            onChangeText={setConfirmPassword}
            placeholder="Repeat new password"
            placeholderTextColor="#9ca3af"
            secureTextEntry={!showPassword}
            editable={!loading}
          />
        </View>

        <TouchableOpacity
          style={[styles.primaryBtn, loading && styles.primaryBtnDisabled]}
          onPress={handleReset}
          disabled={loading}
          activeOpacity={0.8}
        >
          {loading ? (
            <ActivityIndicator color="#fff" />
          ) : (
            <Text style={styles.primaryBtnText}>Reset Password</Text>
          )}
        </TouchableOpacity>

        <TouchableOpacity
          style={styles.backBtn}
          onPress={() => setStep("info")}
          activeOpacity={0.7}
        >
          <Text style={styles.backBtnText}>Back</Text>
        </TouchableOpacity>
      </ScrollView>
    </KeyboardAvoidingView>
  );
}

function StepRow({ number, text }: { number: string; text: string }) {
  return (
    <View style={styles.stepRow}>
      <View style={styles.stepNum}>
        <Text style={styles.stepNumText}>{number}</Text>
      </View>
      <Text style={styles.stepText}>{text}</Text>
    </View>
  );
}

const styles = StyleSheet.create({
  container: { flex: 1, backgroundColor: "#f9fafb" },
  content: { padding: 24, paddingTop: 32, gap: 16, alignItems: "stretch" },
  iconWrap: { alignItems: "center", marginBottom: 8 },
  title: { fontSize: 22, fontWeight: "800", color: "#111827", textAlign: "center" },
  body: { fontSize: 14, color: "#6b7280", textAlign: "center", lineHeight: 20 },

  steps: { backgroundColor: "#fff", borderRadius: 14, borderWidth: 1, borderColor: "#e5e7eb", padding: 16, gap: 14 },
  stepRow: { flexDirection: "row", gap: 12, alignItems: "flex-start" },
  stepNum: {
    width: 24, height: 24, borderRadius: 12,
    backgroundColor: "#eff6ff", justifyContent: "center", alignItems: "center",
    marginTop: 1, flexShrink: 0,
  },
  stepNumText: { fontSize: 12, fontWeight: "700", color: "#2563eb" },
  stepText: { flex: 1, fontSize: 13, color: "#374151", lineHeight: 19 },

  field: { gap: 6 },
  label: { fontSize: 13, fontWeight: "600", color: "#374151" },
  input: {
    backgroundColor: "#fff",
    borderWidth: 1,
    borderColor: "#e5e7eb",
    borderRadius: 10,
    paddingHorizontal: 14,
    paddingVertical: 13,
    fontSize: 15,
    color: "#111827",
    marginBottom: 4,
  },
  passwordRow: { flexDirection: "row", alignItems: "center", gap: 8 },
  eyeBtn: { padding: 8 },

  primaryBtn: {
    backgroundColor: "#2563eb",
    borderRadius: 12,
    paddingVertical: 14,
    alignItems: "center",
    marginTop: 4,
  },
  primaryBtnDisabled: { opacity: 0.5 },
  primaryBtnText: { color: "#fff", fontSize: 16, fontWeight: "600" },

  backBtn: { alignItems: "center", paddingVertical: 10 },
  backBtnText: { fontSize: 15, color: "#6b7280" },
});
